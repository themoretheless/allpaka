const assert = require('node:assert/strict');
const {blocks,diffRows,isDiff} = require('../crates/allpaka-chat/web/content.js');
const patch='diff --git a/a.rs b/a.rs\n--- a/a.rs\n+++ b/a.rs\n@@ -4,2 +4,3 @@\n old\n-gone\n+new\n+extra\n';
const rows=diffRows(patch);
assert.deepEqual(rows.filter(r=>r.kind==='removed').map(r=>r.old),[5]);
assert.deepEqual(rows.filter(r=>r.kind==='added').map(r=>r.next),[5,6]);
assert.equal(rows.filter(r=>r.kind==='file').length,3);
assert.equal(isDiff(patch),true);
assert.equal(isDiff('hello'),false);
assert.equal(isDiff('-a\n+b','patch'),true);
const multiple=diffRows(patch+'diff --git a/b b/b\n--- /dev/null\n+++ b/b\n@@ -0,0 +1 @@\n+created');
assert.equal(multiple.at(-1).next,1);
assert.equal(multiple.at(-1).old,'');
assert.deepEqual(blocks('before\n```diff\n'+patch+'```\nafter').map(b=>b.kind),['text','code','text']);
assert.equal(blocks('```diff\n+streaming')[0].text,'+streaming');
assert.equal(blocks('~~~~js\n```\n~~~~')[0].text,'```');
const tricky=diffRows('@@ -1 +1 @@\n--- old code\n+++ new code');
assert.deepEqual(tricky.map(r=>r.kind),['hunk','removed','added']);
assert.equal(diffRows('+snippet')[0].next,'');
assert.equal(blocks('```html\n<script>alert(1)</script>\n```')[0].text,'<script>alert(1)</script>');
console.log('PASS diff numbering, file boundaries, header-like code, streaming fences, snippets and literal HTML');
