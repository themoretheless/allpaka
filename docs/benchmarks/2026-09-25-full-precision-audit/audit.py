def med(d, f):
    j = json.load(open(f"{d}/{f}.json"))
    return {m["name"]: m["summary"]["median"] for m in j["measurements"]}


def w(d, f):
    """ms/token and tok/s for a run, straight from the JSON."""
    m = med(d, f)
    return 1000.0 / m["decode"], m["decode"], (1000.0 / m["prefill"] if m.get("prefill") else None), m.get("prefill")


def so(d, f):
    t = open(f"{d}/{f}.txt").read()
    o = {}
    g = re.search(r"gpu clock during decode: executing (\d+) ms, scheduling (\d+) ms,"
                  r" round trips \+ idle (\d+) ms \(of (\d+) ms waited\)", t)
    if g:
        o.update(exec_ms=int(g.group(1)), sched_ms=int(g.group(2)),
                 idle_ms=int(g.group(3)), wait_ms=int(g.group(4)))
    h = re.search(r"gpu during decode: (\d+) waits, (\d+) dispatches, encode (\d+) ms", t)
    if h:
        o.update(waits=int(h.group(1)), disp=int(h.group(2)), encode_ms=int(h.group(3)))
    r = re.search(r"decode\s+(\d+) tok in\s+([\d.]+) s\s+([\d.]+) tok/s", t)
    if r:
        o.update(tok=int(r.group(1)), secs=float(r.group(2)), rate=float(r.group(3)))
    return o


def e(d, f):
    s = so(d, f)
    return s["exec_ms"] / s["tok"]


def labels(d, f):
    """The fine per-label decode table printed to stdout: 3 dp, truncation-prone."""
    t = open(f"{d}/{f}.txt").read()
    block = t.split("decode profile, ms/token")[1].split("decode ")[0]
    return {m.group(1): float(m.group(2))
            for m in re.finditer(r"^  (\w+)\s+([\d.]+) \(", block, re.M)}


def coarse(d, f):
    d_ = [m for m in json.load(open(f"{d}/{f}.json"))["measurements"] if m["name"] == "decode"][0]
    return {p["name"]: p["milliseconds"] / 64 for p in d_["phases"]}, 1000.0 / d_["summary"]["median"]


def q1(r):
    """ms/token error bar carried by a 1-decimal tok/s reading."""
    return 1000.0 / (r - 0.05) - 1000.0 / (r + 0.05)


